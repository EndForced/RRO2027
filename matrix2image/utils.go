package matrix2image

import "image/color"

func getRGBAColor(n int) color.RGBA {
	// Палитра из 10 ярких, насыщенных цветов (без черного и белого)
	palette := [10]color.RGBA{
		{255, 0, 0, 255},   // 0: Чистый красный (Red)
		{0, 255, 0, 255},   // 1: Яркий зеленый (Lime)
		{0, 0, 255, 255},   // 2: Насыщенный синий (Blue)
		{255, 255, 0, 255}, // 3: Желтый (Yellow)
		{255, 0, 255, 255}, // 4: Пурпурный (Magenta / Fuchsia)
		{0, 255, 255, 255}, // 5: Голубой (Cyan / Aqua)
		{255, 128, 0, 255}, // 6: Ярко-оранжевый (Orange)
		{128, 0, 255, 255}, // 7: Фиолетовый (Purple)
		{255, 0, 128, 255}, // 8: Розовый (Hot Pink)
		{0, 255, 128, 255}, // 9: Мятно-зеленый (Spring Green)
	}

	// Обрабатываем отрицательные числа, чтобы n % 10 всегда давал индекс от 0 до 9
	idx := n % 10
	if idx < 0 {
		idx += 10
	}

	return palette[idx]
}
